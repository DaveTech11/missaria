/**
 * Replaces any emoji in `text` that has a known premium id with its
 * <tg-emoji> HTML span. Emoji not in the map are left untouched.
 * Caller must send the result with parse_mode: "HTML".
 */
function premiumify(text) {
    if (!text) return text;
    let out = text;
    for (const [emoji, id] of Object.entries(PREMIUM_EMOJI)) {
        // Skip if it's already wrapped (avoid double-wrapping on re-runs)
        out = out.split(emoji).join(`<tg-emoji emoji-id="${id}">${emoji}</tg-emoji>`);
    }
    return out;
}

module.exports = { PREMIUM_EMOJI, premiumify };
