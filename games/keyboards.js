// ============================================================
// KEYBOARD TEXT FORMATTER
// ============================================================

function formatKeyboard(keyboard){



return keyboard

.map(

row =>

row

.filter(Boolean)

.join(" | ")

)

.join("\n");


}





// ============================================================
// CHECK KEYBOARD OPTION
// ============================================================

function hasButton(keyboard,text){



return keyboard.some(

row =>

row.includes(text)

);


}





// ============================================================
// ADD CUSTOM BUTTON
// ============================================================

function addButton(keyboard,button){



keyboard.push(

[button]

);



return keyboard;


}





// ============================================================
// REMOVE BUTTON
// ============================================================

function removeButton(keyboard,button){



return keyboard.map(

row =>

row.filter(

item => item !== button

)

)

.filter(

row => row.length

);


}





