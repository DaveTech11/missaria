// ============================================================
// DYNAMIC BUTTON CREATOR
// ============================================================

function createKeyboard(buttons,columns=2){


const keyboard = [];



for(
let i = 0;
i < buttons.length;
i += columns
){


keyboard.push(

buttons.slice(
i,
i + columns
)

);


}



return keyboard;


}





